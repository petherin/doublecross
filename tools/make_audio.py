#!/usr/bin/env python3
"""Synthesises every sound effect and the music loop for Double Cross.

All audio in the game is generated by this script (no samples), so it's
original and can be regenerated or tweaked at any time:

    python3 tools/make_audio.py

Writes 16-bit mono WAVs (effects) and an Ogg Vorbis loop (music) into
assets/audio/. Needs numpy, and ffmpeg for the Ogg encoding.

The effects are built from simple physical models: struck objects are sums of
decaying partials (wood knocks, metal tinks), thuds are pitch-dropping sine
bodies, explosions layer a crack, a punch, sub-bass, a closing-down noise body,
rumble and falling debris, with saturation and a synthetic room reverb.
"""
import os
import sys
import subprocess
import wave

import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
rng = np.random.default_rng(1985)


# ------------------------------------------------------------------ building blocks

def t_axis(seconds):
    return np.arange(int(SR * seconds)) / SR


def env(n, attack=0.005, decay=None, release=0.05, sustain=1.0, curve=3.0):
    """Attack / exponential decay envelope of n samples."""
    e = np.ones(n)
    a = max(1, int(attack * SR))
    e[:a] = np.linspace(0, 1, a)
    if decay is not None:
        t = np.arange(n - a) / SR
        e[a:] = sustain + (1 - sustain) * np.exp(-t * curve / decay)
    r = min(n, int(release * SR))
    if r > 0:
        e[-r:] *= np.linspace(1, 0, r)
    return e


def noise(seconds):
    return rng.uniform(-1, 1, int(SR * seconds))


def lowpass(x, cutoff):
    """One-pole low-pass; cutoff may be a number or an array (sweeps)."""
    cut = np.broadcast_to(np.asarray(cutoff, dtype=float), x.shape)
    a = 1.0 - np.exp(-2 * np.pi * cut / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += a[i] * (x[i] - acc)
        y[i] = acc
    return y


def highpass(x, cutoff):
    return x - lowpass(x, cutoff)


def bandpass(x, lo, hi):
    return lowpass(highpass(x, lo), hi)


def sine(freq, seconds, phase=0.0):
    t = t_axis(seconds)
    f = np.broadcast_to(np.asarray(freq, dtype=float), t.shape)
    return np.sin(2 * np.pi * np.cumsum(f) / SR + phase)


def pluck(freq, seconds, damping=0.996):
    """Karplus-Strong plucked string."""
    n = int(SR * seconds)
    period = max(2, int(SR / freq))
    buf = rng.uniform(-1, 1, period)
    out = np.empty(n)
    for i in range(n):
        out[i] = buf[i % period]
        buf[i % period] = damping * 0.5 * (buf[i % period] + buf[(i + 1) % period])
    return out


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def pad(x, seconds):
    return np.concatenate([x, np.zeros(int(SR * seconds))])


def normalise(x, peak=0.9):
    m = np.max(np.abs(x))
    return x if m == 0 else x / m * peak


ONLY = set(a for a in sys.argv[1:] if not a.startswith("-"))


def save_wav(name, x, peak=0.9):
    if ONLY and name not in ONLY:
        return
    os.makedirs(OUT, exist_ok=True)
    data = (np.clip(normalise(x, peak), -1, 1) * 32767).astype(np.int16)
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def note(name):
    """'A4' -> Hz (with sharps as # and flats as b)."""
    names = {"C": -9, "D": -7, "E": -5, "F": -4, "G": -2, "A": 0, "B": 2}
    semis = names[name[0]]
    rest = name[1:]
    if rest.startswith("#"):
        semis += 1
        rest = rest[1:]
    elif rest.startswith("b"):
        semis -= 1
        rest = rest[1:]
    return 440.0 * 2 ** ((semis + (int(rest) - 4) * 12) / 12)


def bell(freq, seconds, bright=0.4):
    t = t_axis(seconds)
    x = np.sin(2 * np.pi * freq * t) + bright * np.sin(2 * np.pi * freq * 2.76 * t) * np.exp(-t * 6)
    x += 0.25 * np.sin(2 * np.pi * freq * 5.4 * t) * np.exp(-t * 12)
    return x * env(len(t), 0.002, seconds * 0.5, 0.05)


# ------------------------------------------------------------------ physical-ish DSP

def biquad(x, kind, freq, q=0.707, gain_db=0.0):
    """RBJ biquad filter: lowpass, highpass, bandpass or peak."""
    w0 = 2 * np.pi * freq / SR
    alpha = np.sin(w0) / (2 * q)
    cw = np.cos(w0)
    A = 10 ** (gain_db / 40)
    if kind == "lowpass":
        b = [(1 - cw) / 2, 1 - cw, (1 - cw) / 2]
        a = [1 + alpha, -2 * cw, 1 - alpha]
    elif kind == "highpass":
        b = [(1 + cw) / 2, -(1 + cw), (1 + cw) / 2]
        a = [1 + alpha, -2 * cw, 1 - alpha]
    elif kind == "bandpass":
        b = [alpha, 0, -alpha]
        a = [1 + alpha, -2 * cw, 1 - alpha]
    else:  # peak
        b = [1 + alpha * A, -2 * cw, 1 - alpha * A]
        a = [1 + alpha / A, -2 * cw, 1 - alpha / A]
    b = [v / a[0] for v in b]
    a1, a2 = a[1] / a[0], a[2] / a[0]
    y = np.zeros_like(x)
    x1 = x2 = y1 = y2 = 0.0
    b0, b1, b2 = b
    for i in range(len(x)):
        xi = x[i]
        yi = b0 * xi + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
        x2, x1, y2, y1 = x1, xi, y1, yi
        y[i] = yi
    return y


def brown(seconds):
    """Brown (red) noise: deep, rumbly."""
    w = rng.normal(0, 1, int(SR * seconds))
    b = np.cumsum(w)
    b -= lowpass(b, 8.0)
    return b / (np.max(np.abs(b)) + 1e-9)


def pink(seconds):
    n = int(SR * seconds)
    f = np.fft.rfftfreq(n, 1 / SR)
    spec = (rng.normal(size=len(f)) + 1j * rng.normal(size=len(f))) / np.sqrt(np.maximum(f, 20.0))
    x = np.fft.irfft(spec, n)
    return x / (np.max(np.abs(x)) + 1e-9)


def modal(freqs, decays, amps, seconds, jitter=0.0):
    """Struck object: a sum of exponentially decaying partials."""
    t = t_axis(seconds)
    out = np.zeros_like(t)
    for f, d, a in zip(freqs, decays, amps):
        f *= 1 + rng.uniform(-jitter, jitter)
        out += a * np.sin(2 * np.pi * f * t + rng.uniform(0, 6.28)) * np.exp(-t / d)
    return out


def click(seconds=0.004, hp=2000.0):
    n = noise(seconds) * np.exp(-np.arange(int(SR * seconds)) / (SR * seconds / 4))
    return highpass(n, hp)


def saturate(x, drive=2.0):
    return np.tanh(x * drive) / np.tanh(drive)


def at(x, seconds):
    """Delays x by `seconds` (for building sequences with mix())."""
    return np.concatenate([np.zeros(int(SR * seconds)), x])


def reverb(x, length=1.2, wet=0.3, damp=3000.0, early=(0.011, 0.023, 0.037, 0.053, 0.071)):
    """Synthetic room: early reflections plus a decaying, darkening noise tail."""
    n = int(SR * length)
    t = np.arange(n) / SR
    tail = rng.normal(0, 1, n) * np.exp(-t * 6.9 / length)
    tail = lowpass(tail, damp * np.exp(-t * 1.5) + 200)
    ir = np.zeros(n)
    for i, d in enumerate(early):
        ir[int(d * SR)] += 0.6 / (i + 1)
    ir += tail * 0.12
    m = len(x) + n
    size = 1 << (m - 1).bit_length()
    y = np.fft.irfft(np.fft.rfft(x, size) * np.fft.rfft(ir, size), size)[:m]
    y /= np.max(np.abs(y)) + 1e-9
    dry = np.concatenate([x / (np.max(np.abs(x)) + 1e-9), np.zeros(n)])
    return dry * (1 - wet) + y * wet


# ------------------------------------------------------------------ sound effects

def wood_knock(f0=180.0, strength=1.0):
    k = modal([f0, f0 * 2.28, f0 * 3.9, f0 * 6.1], [0.07, 0.04, 0.025, 0.015], [1, 0.6, 0.35, 0.2], 0.3, 0.04)
    return mix(k, click(0.003, 1500) * 0.6) * strength


def metal_tink(f0=1800.0, strength=1.0):
    return modal([f0, f0 * 1.47, f0 * 2.13, f0 * 2.94], [0.12, 0.08, 0.05, 0.03], [1, 0.7, 0.5, 0.3], 0.4, 0.05) * strength


def thud(f0=70.0, length=0.35, strength=1.0):
    t = t_axis(length)
    body = np.sin(2 * np.pi * np.cumsum(f0 * (1 + 1.5 * np.exp(-t * 30))) / SR) * np.exp(-t * 14)
    return (body + lowpass(noise(length), 900) * np.exp(-t * 40) * 0.6) * strength


def drawer_slide(length=0.32):
    n = brown(length) * 0.5 + noise(length) * 0.25
    n = biquad(n, "bandpass", 700, 0.9)
    rattle = 1 + 0.6 * np.sign(np.sin(2 * np.pi * 38 * t_axis(length)))
    return n * rattle * env(int(SR * length), 0.03, None, 0.06)


