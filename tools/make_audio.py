#!/usr/bin/env python3
"""Synthesises every sound effect and the music loop for Double Cross.

All audio in the game is generated by this script (no samples), so it's
original and can be regenerated or tweaked at any time:

    python3 tools/make_audio.py

Writes 16-bit mono WAVs (effects) and an Ogg Vorbis loop (music) into
assets/audio/. Needs numpy, and ffmpeg for the Ogg encoding.
"""
import os
import subprocess
import wave

import numpy as np

SR = 22050
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
rng = np.random.default_rng(1985)


# ------------------------------------------------------------------ building blocks

def t_axis(seconds):
    return np.arange(int(SR * seconds)) / SR


def env(n, attack=0.005, decay=None, release=0.05, sustain=1.0, curve=3.0):
    """Attack / exponential decay envelope of n samples."""
    e = np.ones(n)
    a = max(1, int(attack * SR))
    e[:a] = np.linspace(0, 1, a)
    if decay is not None:
        t = np.arange(n - a) / SR
        e[a:] = sustain + (1 - sustain) * np.exp(-t * curve / decay)
    r = min(n, int(release * SR))
    if r > 0:
        e[-r:] *= np.linspace(1, 0, r)
    return e


def noise(seconds):
    return rng.uniform(-1, 1, int(SR * seconds))


def lowpass(x, cutoff):
    """One-pole low-pass; cutoff may be a number or an array (sweeps)."""
    cut = np.broadcast_to(np.asarray(cutoff, dtype=float), x.shape)
    a = 1.0 - np.exp(-2 * np.pi * cut / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += a[i] * (x[i] - acc)
        y[i] = acc
    return y


def highpass(x, cutoff):
    return x - lowpass(x, cutoff)


def bandpass(x, lo, hi):
    return lowpass(highpass(x, lo), hi)


def sine(freq, seconds, phase=0.0):
    t = t_axis(seconds)
    f = np.broadcast_to(np.asarray(freq, dtype=float), t.shape)
    return np.sin(2 * np.pi * np.cumsum(f) / SR + phase)


def pluck(freq, seconds, damping=0.996):
    """Karplus-Strong plucked string."""
    n = int(SR * seconds)
    period = max(2, int(SR / freq))
    buf = rng.uniform(-1, 1, period)
    out = np.empty(n)
    for i in range(n):
        out[i] = buf[i % period]
        buf[i % period] = damping * 0.5 * (buf[i % period] + buf[(i + 1) % period])
    return out


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def pad(x, seconds):
    return np.concatenate([x, np.zeros(int(SR * seconds))])


def normalise(x, peak=0.9):
    m = np.max(np.abs(x))
    return x if m == 0 else x / m * peak


def save_wav(name, x, peak=0.9):
    os.makedirs(OUT, exist_ok=True)
    data = (np.clip(normalise(x, peak), -1, 1) * 32767).astype(np.int16)
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def note(name):
    """'A4' -> Hz (with sharps as # and flats as b)."""
    names = {"C": -9, "D": -7, "E": -5, "F": -4, "G": -2, "A": 0, "B": 2}
    semis = names[name[0]]
    rest = name[1:]
    if rest.startswith("#"):
        semis += 1
        rest = rest[1:]
    elif rest.startswith("b"):
        semis -= 1
        rest = rest[1:]
    return 440.0 * 2 ** ((semis + (int(rest) - 4) * 12) / 12)


def bell(freq, seconds, bright=0.4):
    t = t_axis(seconds)
    x = np.sin(2 * np.pi * freq * t) + bright * np.sin(2 * np.pi * freq * 2.76 * t) * np.exp(-t * 6)
    x += 0.25 * np.sin(2 * np.pi * freq * 5.4 * t) * np.exp(-t * 12)
    return x * env(len(t), 0.002, seconds * 0.5, 0.05)


# ------------------------------------------------------------------ sound effects

def sfx():
    # Footsteps: soft heel thump + a little scuff.
    for i, f in enumerate([95, 110]):
        n = t_axis(0.09)
        thump = np.sin(2 * np.pi * f * n * (1 - n * 3)) * env(len(n), 0.002, 0.03, 0.01)
        scuff = bandpass(noise(0.09), 1500, 5000) * env(len(n), 0.001, 0.02, 0.01) * 0.5
        save_wav("step%d" % (i + 1), thump + scuff, 0.5)

    # Rummaging: a drawer sliding, papers shuffling.
    parts = []
    for k in range(6):
        burst = bandpass(noise(0.08), 800 + k * 300, 4000) * env(int(SR * 0.08), 0.01, 0.04, 0.02)
        parts.append(np.concatenate([np.zeros(int(SR * (0.06 + k * 0.1))), burst]))
    slide = bandpass(noise(0.3), 200, 1200) * env(int(SR * 0.3), 0.05, 0.2, 0.05) * 0.7
    save_wav("rummage", mix(slide, *parts), 0.55)

    # Found an item: rising vibraphone arpeggio.
    notes = ["D5", "F#5", "A5", "D6"]
    out = np.zeros(int(SR * 1.2))
    for i, nm in enumerate(notes):
        b = bell(note(nm), 0.8)
        s = int(SR * i * 0.08)
        out[s: s + len(b)] += b[: len(out) - s]
    save_wav("found", out, 0.7)

    # Found a gadget: metallic double ding.
    save_wav("gadget", mix(bell(note("A5"), 0.7, 0.9), np.concatenate([np.zeros(int(SR * 0.12)), bell(note("E6"), 0.6, 0.9)])), 0.6)

    # Nothing here: two soft descending notes.
    a = bell(note("E4"), 0.25, 0.1)
    b = bell(note("C4"), 0.35, 0.1)
    save_wav("nothing", mix(a, np.concatenate([np.zeros(int(SR * 0.12)), b])), 0.45)

    # Trap set: mechanical click-clack.
    c1 = highpass(noise(0.02), 2000) * env(int(SR * 0.02), 0.0005, 0.005, 0.005)
    c2 = highpass(noise(0.03), 1200) * env(int(SR * 0.03), 0.0005, 0.008, 0.005)
    save_wav("trap_set", mix(c1, np.concatenate([np.zeros(int(SR * 0.09)), c2]), np.concatenate([np.zeros(int(SR * 0.2)), c1 * 0.7])), 0.6)

    # Bomb: crack, deep boom, rumbling smoke and crackle.
    n = t_axis(2.4)
    crack = highpass(noise(0.05), 1500) * env(int(SR * 0.05), 0.0005, 0.02, 0.01)
    sweep = 3000 * np.exp(-n * 3.5) + 120
    body = lowpass(noise(2.4), sweep) * env(len(n), 0.003, 0.8, 0.3) * 1.6
    sub = np.sin(2 * np.pi * (55 * np.exp(-n * 1.5) + 30) * n) * env(len(n), 0.002, 0.5, 0.3) * 1.2
    crackle = np.zeros(len(n))
    for _ in range(60):
        s = int(rng.uniform(0.1, 1.8) * SR)
        crackle[s: s + 60] += rng.uniform(-1, 1, 60) * np.exp(-np.arange(60) / 10) * rng.uniform(0.1, 0.4)
    save_wav("boom", mix(crack, body, sub, crackle), 0.95)

    # Spring trap: cartoon boing.
    n = t_axis(0.9)
    f = 180 + 120 * np.sin(2 * np.pi * 9 * n) * np.exp(-n * 3) + 140 * np.exp(-n * 4)
    boing = sine(f, 0.9) * env(len(n), 0.003, 0.5, 0.1)
    save_wav("boing", boing + 0.3 * sine(f * 2, 0.9) * env(len(n), 0.003, 0.3, 0.1), 0.7)

    # Tripwire: taut wire twang + snap.
    tw = pluck(note("A3"), 0.8, 0.997)
    snap = highpass(noise(0.03), 2500) * env(int(SR * 0.03), 0.0005, 0.01, 0.005)
    save_wav("twang", mix(tw * env(len(tw), 0.001, 0.4, 0.1), snap), 0.75)

    # Cosh swing: whoosh.
    n = t_axis(0.28)
    wh = bandpass(noise(0.28), 300 + 2500 * np.sin(np.pi * n / 0.28), 4000) * np.sin(np.pi * n / 0.28) ** 2
    save_wav("swing", wh, 0.5)

    # Hit: punchy thud.
    n = t_axis(0.25)
    thud = np.sin(2 * np.pi * (140 * np.exp(-n * 20) + 60) * n) * env(len(n), 0.001, 0.08, 0.05)
    smack = bandpass(noise(0.05), 800, 6000) * env(int(SR * 0.05), 0.0005, 0.015, 0.01)
    save_wav("hit", mix(thud * 1.2, smack), 0.85)

    # Taken out: big WHAM + a little cartoon bird tweet.
    n = t_axis(0.5)
    wham = np.sin(2 * np.pi * (90 * np.exp(-n * 8) + 45) * n) * env(len(n), 0.001, 0.2, 0.1)
    crash = bandpass(noise(0.5), 2000, 9000) * env(len(n), 0.001, 0.15, 0.1) * 0.6
    tweets = np.zeros(int(SR * 1.3))
    for k in range(3):
        nn = t_axis(0.09)
        tw = sine(2600 + 900 * np.sin(np.pi * nn / 0.09), 0.09) * env(len(nn), 0.005, 0.05, 0.02) * 0.25
        s = int(SR * (0.55 + k * 0.22))
        tweets[s: s + len(tw)] += tw
    save_wav("down", mix(wham * 1.3, crash, tweets), 0.9)

    # Dart pistol: pneumatic pfft + tick.
    pf = bandpass(noise(0.12), 600, 5000) * env(int(SR * 0.12), 0.001, 0.04, 0.03)
    tick = highpass(noise(0.01), 3000) * env(int(SR * 0.01), 0.0005, 0.003, 0.003)
    save_wav("dart", mix(pf, tick), 0.6)

    # Door: pneumatic sliding hiss.
    n = t_axis(0.45)
    hiss = bandpass(noise(0.45), 1500, 7000) * np.sin(np.pi * n / 0.45) ** 1.5 * 0.6
    clunk = np.sin(2 * np.pi * 80 * n) * env(len(n), 0.001, 0.05, 0.05) * 0.5
    save_wav("door", mix(hiss, np.concatenate([np.zeros(int(SR * 0.3)), clunk[: int(SR * 0.15)]])), 0.4)

    # UI click.
    n = t_axis(0.05)
    save_wav("click", np.sin(2 * np.pi * 1800 * n) * env(len(n), 0.001, 0.01, 0.01), 0.4)

    # Exit locked: two-tone buzzer.
    n = t_axis(0.35)
    buzz = np.sign(np.sin(2 * np.pi * 110 * n)) * 0.5 + np.sign(np.sin(2 * np.pi * 116 * n)) * 0.5
    save_wav("locked", lowpass(buzz, 1500) * env(len(n), 0.005, None, 0.05), 0.4)

    # Clock low: tick-tock.
    n = t_axis(0.06)
    save_wav("tick", bandpass(noise(0.06), 2000, 6000) * env(len(n), 0.0005, 0.01, 0.01) + 0.3 * np.sin(2 * np.pi * 1200 * n) * env(len(n), 0.0005, 0.01, 0.01), 0.5)

    # Win: jazzy major-seventh flourish.
    out = np.zeros(int(SR * 2.4))
    for i, nm in enumerate(["D4", "F#4", "A4", "C#5", "E5", "A5"]):
        b = bell(note(nm), 1.6, 0.5)
        s = int(SR * i * 0.1)
        out[s: s + len(b)] += b[: len(out) - s] * 0.8
    for nm in ["D3", "A3"]:
        p = pluck(note(nm), 2.0, 0.998)
        out[int(SR * 0.6): int(SR * 0.6) + len(p)] += p[: len(out) - int(SR * 0.6)] * 0.6
    save_wav("win", out, 0.8)

    # Lose: sad trombone "wah wah wah wahhh".
    out = []
    for i, (nm, d) in enumerate([("A3", 0.35), ("G#3", 0.35), ("G3", 0.35), ("F#3", 1.1)]):
        n = t_axis(d)
        f = note(nm) * (1 + (0.02 * np.sin(2 * np.pi * 6 * n) if i == 3 else 0))
        saw = 2 * ((np.cumsum(np.broadcast_to(f, n.shape)) / SR) % 1.0) - 1
        wah = lowpass(saw, 400 + 1400 * np.sin(np.pi * n / d)) * env(len(n), 0.03, None, 0.08)
        out.append(wah)
    save_wav("lose", np.concatenate(out), 0.7)


# ------------------------------------------------------------------ music

def music():
    """Original 16-bar spy-jazz loop: walking bass, brushes, vibraphone."""
    bpm = 126
    beat = 60.0 / bpm
    bars = 16
    total = bars * 4 * beat
    out = np.zeros(int(SR * total) + SR)

    def place(x, at, gain=1.0):
        s = int(at * SR)
        e = min(len(out), s + len(x))
        out[s:e] += x[: e - s] * gain

    swing = beat * 2 / 3  # swung eighth offset

    # Chords per bar (root for the bass walk, tones for the vibes).
    prog = ["Dm", "Dm", "Gm", "Gm", "Dm", "Dm", "Eb7", "A7",
            "Dm", "Dm", "Gm", "Gm", "Bb7", "A7", "Dm", "A7"]
    tones = {
        "Dm": ["D", "F", "A", "C"], "Gm": ["G", "Bb", "D", "F"],
        "Eb7": ["Eb", "G", "Bb", "Db"], "A7": ["A", "C#", "E", "G"], "Bb7": ["Bb", "D", "F", "Ab"],
    }

    # Walking bass: root, 3rd, 5th, chromatic approach to the next root.
    for bar, ch in enumerate(prog):
        nxt = tones[prog[(bar + 1) % bars]][0]
        r, t3, t5, _ = tones[ch]
        walk = [r + "2", t3 + "2", t5 + "2", None]
        approach = note(nxt + "2") * (2 ** (-1 / 12) if bar % 2 == 0 else 2 ** (1 / 12))
        for b in range(4):
            f = note(walk[b]) if walk[b] else approach
            p = pluck(f, beat * 1.1, 0.994)
            p = lowpass(p, 900) * env(len(p), 0.004, beat * 0.9, 0.05)
            place(p, (bar * 4 + b) * beat, 0.9)

    # Brushes: swung ride/hat on every beat and the swung "and", snare swish on 2 and 4.
    hat = highpass(noise(0.06), 6000) * env(int(SR * 0.06), 0.001, 0.02, 0.02)
    swish = bandpass(noise(0.25), 1500, 7000) * env(int(SR * 0.25), 0.04, 0.12, 0.08)
    kick_t = t_axis(0.2)
    kick = np.sin(2 * np.pi * (90 * np.exp(-kick_t * 25) + 45) * kick_t) * env(len(kick_t), 0.001, 0.06, 0.05)
    for b in range(bars * 4):
        t = b * beat
        place(hat, t, 0.22)
        if b % 2 == 1:
            place(hat, t + swing, 0.14)
            place(swish, t - 0.02, 0.18)
        if b % 4 == 0:
            place(kick, t, 0.35)

    # Vibraphone: a sneaky, original motif over the first 8 bars, an answer over the last 8.
    motif = [  # (bar, beat offset, note, length in beats)
        (0, 0, "D5", 1), (0, 1.67, "E5", 0.33), (0, 2, "F5", 1.5), (1, 0, "E5", 0.67), (1, 0.67, "D5", 2),
        (2, 0, "Bb4", 1), (2, 1.67, "C5", 0.33), (2, 2, "D5", 1.5), (3, 0, "C5", 0.67), (3, 0.67, "Bb4", 2),
        (4, 0, "A4", 0.67), (4, 0.67, "D5", 0.67), (4, 1.33, "F5", 0.67), (4, 2, "A5", 2),
        (6, 0, "G5", 1), (6, 1, "F5", 0.67), (6, 1.67, "Eb5", 1.33), (7, 0, "E5", 0.67), (7, 0.67, "C#5", 2.5),
        (8, 0, "F5", 1), (8, 1.67, "E5", 0.33), (8, 2, "D5", 1.5), (9, 0, "A4", 3),
        (10, 0, "D5", 0.67), (10, 0.67, "F5", 0.67), (10, 1.33, "G5", 2), (11, 0, "F5", 0.67), (11, 0.67, "D5", 2),
        (12, 0, "Ab5", 1), (12, 1, "F5", 1), (12, 2, "D5", 1), (13, 0, "C#5", 0.67), (13, 0.67, "E5", 0.67),
        (13, 1.33, "G5", 1.5), (14, 0, "F5", 1), (14, 1, "E5", 0.67), (14, 1.67, "D5", 2.33),
    ]
    for bar, off, nm, ln in motif:
        n = t_axis(ln * beat + 0.8)
        trem = 1 + 0.25 * np.sin(2 * np.pi * 5.5 * n)
        v = bell(note(nm), ln * beat + 0.8, 0.25) * trem
        place(v, (bar * 4 + off) * beat, 0.38)

    # Soft organ pad comping the chords on beat 1 (keeps it moody).
    for bar, ch in enumerate(prog):
        n = t_axis(beat * 3.5)
        pad_x = sum(np.sin(2 * np.pi * note(t + "3") * n) for t in tones[ch][1:])
        place(lowpass(pad_x, 1200) * env(len(n), 0.08, None, 0.4) * 0.12, bar * 4 * beat)

    # Make the loop seamless: fold the tail back into the start.
    loop_len = int(SR * total)
    tail = out[loop_len:]
    out = out[:loop_len]
    out[: len(tail)] += tail
    data = np.clip(normalise(out, 0.8), -1, 1)
    tmp = os.path.join(OUT, "_music.wav")
    with wave.open(tmp, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((data * 32767).astype(np.int16).tobytes())
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-c:a", "libvorbis", "-q:a", "4",
                    os.path.join(OUT, "music.ogg")], check=True)
    os.remove(tmp)


if __name__ == "__main__":
    sfx()
    music()
    print("audio written to", os.path.abspath(OUT))
