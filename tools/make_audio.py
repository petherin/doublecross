def music():
    """Original 16-bar spy-jazz loop: walking bass, brushes, vibraphone.

    Written as three loops of exactly the same length that the game plays
    together and mixes on the fly:
      music.ogg          the bed: bass, brushes, vibes and organ pad
      music_tension.ogg  shaker, low toms and a tremolo swell (a rival is near)
      music_hurry.ogg    driving hats, brass stabs and a rising riff (clock low)
    """
    bpm = 126
    beat = 60.0 / bpm
    bars = 16
    total = bars * 4 * beat
    out = np.zeros(int(SR * total) + SR)
    tension = np.zeros_like(out)
    hurry = np.zeros_like(out)

    def place(x, at, gain=1.0, into=None):
        buf = out if into is None else into
        s = int(at * SR)
        e = min(len(buf), s + len(x))
        buf[s:e] += x[: e - s] * gain

    swing = beat * 2 / 3  # swung eighth offset

    # Chords per bar (root for the bass walk, tones for the vibes).
    prog = ["Dm", "Dm", "Gm", "Gm", "Dm", "Dm", "Eb7", "A7",
            "Dm", "Dm", "Gm", "Gm", "Bb7", "A7", "Dm", "A7"]
    tones = {
        "Dm": ["D", "F", "A", "C"], "Gm": ["G", "Bb", "D", "F"],
        "Eb7": ["Eb", "G", "Bb", "Db"], "A7": ["A", "C#", "E", "G"], "Bb7": ["Bb", "D", "F", "Ab"],
    }

    # Walking bass: root, 3rd, 5th, chromatic approach to the next root.
    for bar, ch in enumerate(prog):
        nxt = tones[prog[(bar + 1) % bars]][0]
        r, t3, t5, _ = tones[ch]
        walk = [r + "2", t3 + "2", t5 + "2", None]
        approach = note(nxt + "2") * (2 ** (-1 / 12) if bar % 2 == 0 else 2 ** (1 / 12))
        for b in range(4):
            f = note(walk[b]) if walk[b] else approach
            p = pluck(f, beat * 1.1, 0.994)
            p = lowpass(p, 900) * env(len(p), 0.004, beat * 0.9, 0.05)
            place(p, (bar * 4 + b) * beat, 0.9)

    # Brushes: swung ride/hat on every beat and the swung "and", snare swish on 2 and 4.
    hat = highpass(noise(0.06), 6000) * env(int(SR * 0.06), 0.001, 0.02, 0.02)
    swish = bandpass(noise(0.25), 1500, 7000) * env(int(SR * 0.25), 0.04, 0.12, 0.08)
    kick_t = t_axis(0.2)
    kick = np.sin(2 * np.pi * (90 * np.exp(-kick_t * 25) + 45) * kick_t) * env(len(kick_t), 0.001, 0.06, 0.05)
    for b in range(bars * 4):
        t = b * beat
        place(hat, t, 0.22)
        if b % 2 == 1:
            place(hat, t + swing, 0.14)
            place(swish, t - 0.02, 0.18)
        if b % 4 == 0:
            place(kick, t, 0.35)

    # Vibraphone: a sneaky, original motif over the first 8 bars, an answer over the last 8.
    motif = [  # (bar, beat offset, note, length in beats)
        (0, 0, "D5", 1), (0, 1.67, "E5", 0.33), (0, 2, "F5", 1.5), (1, 0, "E5", 0.67), (1, 0.67, "D5", 2),
        (2, 0, "Bb4", 1), (2, 1.67, "C5", 0.33), (2, 2, "D5", 1.5), (3, 0, "C5", 0.67), (3, 0.67, "Bb4", 2),
        (4, 0, "A4", 0.67), (4, 0.67, "D5", 0.67), (4, 1.33, "F5", 0.67), (4, 2, "A5", 2),
        (6, 0, "G5", 1), (6, 1, "F5", 0.67), (6, 1.67, "Eb5", 1.33), (7, 0, "E5", 0.67), (7, 0.67, "C#5", 2.5),
        (8, 0, "F5", 1), (8, 1.67, "E5", 0.33), (8, 2, "D5", 1.5), (9, 0, "A4", 3),
        (10, 0, "D5", 0.67), (10, 0.67, "F5", 0.67), (10, 1.33, "G5", 2), (11, 0, "F5", 0.67), (11, 0.67, "D5", 2),
        (12, 0, "Ab5", 1), (12, 1, "F5", 1), (12, 2, "D5", 1), (13, 0, "C#5", 0.67), (13, 0.67, "E5", 0.67),
        (13, 1.33, "G5", 1.5), (14, 0, "F5", 1), (14, 1, "E5", 0.67), (14, 1.67, "D5", 2.33),
    ]
    for bar, off, nm, ln in motif:
        n = t_axis(ln * beat + 0.8)
        trem = 1 + 0.25 * np.sin(2 * np.pi * 5.5 * n)
        v = bell(note(nm), ln * beat + 0.8, 0.25) * trem
        place(v, (bar * 4 + off) * beat, 0.38)

    # Soft organ pad comping the chords on beat 1 (keeps it moody).
    for bar, ch in enumerate(prog):
        n = t_axis(beat * 3.5)
        pad_x = sum(np.sin(2 * np.pi * note(t + "3") * n) for t in tones[ch][1:])
        place(lowpass(pad_x, 1200) * env(len(n), 0.08, None, 0.4) * 0.12, bar * 4 * beat)

    # ---- Tension layer: a rival is in the room.
    shaker = bandpass(noise(0.05), 3000, 9000) * env(int(SR * 0.05), 0.002, 0.02, 0.02)
    tom_t = t_axis(0.35)
    tom = np.sin(2 * np.pi * (120 * np.exp(-tom_t * 6) + 70) * tom_t) * env(len(tom_t), 0.002, 0.2, 0.1)
    for b in range(bars * 4):
        t = b * beat
        place(shaker, t, 1.1, tension)
        place(shaker, t + swing, 0.7, tension)
        if b % 8 == 7:
            place(tom, t + swing, 0.5, tension)
            place(tom, t + beat * 0.5 + swing, 0.35, tension)
    for bar, ch in enumerate(prog):
        # Low tremolo swell on the chord's root and fifth, rising through the bar.
        n = t_axis(beat * 4)
        r, _, t5, _ = tones[ch]
        swell = sum(np.sin(2 * np.pi * note(x + "2") * n) for x in (r, t5))
        swell = lowpass(swell, 500) * (0.7 + 0.3 * np.sign(np.sin(2 * np.pi * 7.0 * n)))
        place(swell * env(len(n), 1.2, None, 0.5) * 0.05, bar * 4 * beat, 1.0, tension)

    # ---- Hurry layer: the clock is nearly out.
    tick = highpass(noise(0.03), 7000) * env(int(SR * 0.03), 0.001, 0.012, 0.01)
    for b in range(bars * 16):
        place(tick, b * beat / 4, 0.28 if b % 4 == 0 else 0.16, hurry)
    for bar, ch in enumerate(prog):
        # Brass stabs: a saw-wave chord, short and punchy, on 1 and the and-of-2.
        for off in (0.0, 1.5):
            n = t_axis(beat * 0.45)
            stab = sum(2 * ((note(x + "3") * n) % 1.0) - 1 for x in tones[ch][:3])
            stab = lowpass(stab, 1800 - 1200 * n / n[-1]) * env(len(n), 0.01, beat * 0.3, 0.05)
            place(saturate(stab, 1.6) * 0.22, (bar * 4 + off) * beat, 1.0, hurry)
        # Rising eighth-note riff over the chord tones.
        for k in range(8):
            x = tones[ch][k % 4] + ("5" if k < 4 else "6")
            pl = pluck(note(x), beat * 0.6, 0.992) * env(int(SR * beat * 0.6), 0.002, beat * 0.4, 0.05)
            place(pl, (bar * 4 + k * 0.5) * beat, 0.3, hurry)

    for name, buf in (("music", out), ("music_tension", tension), ("music_hurry", hurry)):
        _write_loop(name, buf, int(SR * total))


def ambience():
    """Quiet room-tone loops, one per kind of room (the game picks by name):
      amb_hvac      air-conditioning: a breathy low roar and a 50 Hz hum
      amb_machines  server racks: fan whine, a hum and relays clicking
      amb_pipes     plumbing: a drone, drips into a puddle, a pipe creak
    """
    L = 16.0
    n = int(SR * L)
    rng = np.random.default_rng(11)

    def make(length=L):
        return np.zeros(int(SR * length) + SR)

    def put(buf, x, at, gain=1.0):
        s = int(at * SR)
        e = min(len(buf), s + len(x))
        buf[s:e] += x[: e - s] * gain

    t = t_axis(L + 1.0)
    # HVAC: brown noise through a low band, breathing slowly, plus mains hum.
    hvac = make()
    roar = bandpass(brown(L + 1.0), 40, 600) * (0.8 + 0.2 * np.sin(2 * np.pi * t / 8.0))
    hum = 0.25 * np.sin(2 * np.pi * 50 * t) + 0.12 * np.sin(2 * np.pi * 100 * t)
    hvac += roar * 1.0 + hum * 0.35
    _write_loop("amb_hvac", _crossfade(hvac, n), n)

    # Server room: a steady fan whine with a slow beat, hum, relay clicks.
    machines = make()
    whine = sum(np.sin(2 * np.pi * f * t) / k for k, f in enumerate([1180.0, 1186.0, 2364.0], 1))
    machines += whine * 0.05 + bandpass(noise(L + 1.0), 300, 3000) * 0.18 + hum * 0.3
    for _ in range(14):
        at = rng.uniform(0, L)
        put(machines, mix(click(0.004, 2500) * 0.6, metal_tink(rng.uniform(2500, 4200), 0.15)), at)
    _write_loop("amb_machines", _crossfade(machines, n), n)

    # Pipes: a low drone, drips plinking into a puddle, an occasional creak.
    pipes = make()
    pipes += bandpass(brown(L + 1.0), 30, 300) * 0.6 + np.sin(2 * np.pi * 62 * t) * 0.05
    for _ in range(9):
        at = rng.uniform(0, L)
        f = rng.uniform(900, 1700)
        dn = t_axis(0.25)
        drip = np.sin(2 * np.pi * (f + 900 * np.exp(-dn * 30)) * dn) * env(len(dn), 0.001, 0.08, 0.05)
        put(pipes, reverb(drip, 0.8, 0.4), at, 0.5)
    for at in (3.5, 11.0):
        cn = t_axis(0.9)
        creak = np.sin(2 * np.pi * np.cumsum(140 + 40 * np.sin(2 * np.pi * 3 * cn)) / SR)
        creak = saturate(creak * (0.5 + 0.5 * np.sign(np.sin(2 * np.pi * 23 * cn))), 2.0)
        put(pipes, lowpass(creak, 900) * env(len(cn), 0.1, None, 0.3) * 0.25, at)
    _write_loop("amb_pipes", _crossfade(pipes, n), n)


def _crossfade(buf, loop_len, fade=1.0):
    """Turns a continuous sound into a seamless loop: the part after
    loop_len is faded out over the start while the start fades in (equal
    power), so the loop point has no bump or gap."""
    f = int(SR * fade)
    out = buf[:loop_len].copy()
    tail = buf[loop_len: loop_len + f]
    k = np.linspace(0.0, 1.0, len(tail))
    out[: len(tail)] = out[: len(tail)] * np.sqrt(k) + tail * np.sqrt(1.0 - k)
    return out


def _write_loop(name, buf, loop_len):
    """Folds the tail back into the start so the loop is seamless, then
    writes an Ogg Vorbis file of exactly loop_len samples."""
    tail = buf[loop_len:]
    buf = buf[:loop_len].copy()
    buf[: len(tail)] += tail
    data = np.clip(normalise(buf, 0.8), -1, 1)
    tmp = os.path.join(OUT, "_%s.wav" % name)
    with wave.open(tmp, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((data * 32767).astype(np.int16).tobytes())
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-c:a", "libvorbis", "-q:a", "4",
                    os.path.join(OUT, name + ".ogg")], check=True)
    os.remove(tmp)


